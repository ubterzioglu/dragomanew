import { LOCALES } from '../../i18n/locales'
import { localePath } from '../../i18n/pages'

/**
 * Search and AI answer crawlers named explicitly at launch (plan §4): some of them skip the `*` group
 * or are blocked by default host rules, so an explicit Allow makes the intent unambiguous.
 * scripts/check-dist.mjs keeps its own copy of this list on purpose, to catch an edit here.
 */
export const NAMED_CRAWLERS = [
  'GPTBot',
  'OAI-SearchBot',
  'ClaudeBot',
  'Claude-Web',
  'anthropic-ai',
  'PerplexityBot',
  'Google-Extended',
  'Bingbot',
  'Applebot',
] as const

/** Never worth crawling: the staff panel, the Stage A review index and the participant forms (noindex for good). */
export function crawlExclusions(): string[] {
  return ['/panel/', '/__demo/', ...LOCALES.map((locale) => localePath(locale, 'participantForm'))]
}

interface RobotsOptions {
  publicRelease: boolean
  origin: string
}

function group(agents: readonly string[], exclusions: readonly string[]): string[] {
  return [...agents.map((agent) => `User-agent: ${agent}`), 'Allow: /', ...exclusions.map((path) => `Disallow: ${path}`)]
}

/** robots.txt for the build: Stage A shuts every crawler out (SEO-05); a release opens the site and lists the sitemap. */
export function buildRobotsTxt({ publicRelease, origin }: RobotsOptions): string {
  if (!publicRelease) {
    return [
      '# Stage A preview with sample content: keep everything out of search indexes (V6 §4.8, SEO-05).',
      '# Generated by scripts/postbuild.mjs; a build with VITE_PUBLIC_RELEASE=true opens the site.',
      'User-agent: *',
      'Disallow: /',
      '',
    ].join('\n')
  }
  const exclusions = crawlExclusions()
  return [
    '# Generated by scripts/postbuild.mjs (VITE_PUBLIC_RELEASE=true).',
    ...group(['*'], exclusions),
    '',
    ...group(NAMED_CRAWLERS, exclusions),
    '',
    `Sitemap: ${origin}/sitemap.xml`,
    '',
  ].join('\n')
}
